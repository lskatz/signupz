"""One small Jekyll page per list, so each list has its own URL: /lists/<id>/.

The page is only a stub; _layouts/signup.html renders the list from _data.
"""

from __future__ import annotations

from pathlib import Path

from .model import SignupList

PAGES_DIR = "lists"
MARK = "# Generated by signupz. One page per list; rewritten automatically, don't edit."


def stub_text(list_id: str) -> str:
    return f"---\n{MARK}\nlayout: signup\nlist_id: {list_id}\npermalink: /lists/{list_id}/\n---\n"


def write_stub(root: Path, list_id: str) -> bool:
    """Create or fix the page for one list. Returns True if the file changed."""
    path = root / PAGES_DIR / f"{list_id}.html"
    want = stub_text(list_id)
    if path.exists() and path.read_text(encoding="utf-8") == want:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(want, encoding="utf-8")
    return True


def sync_pages(root: Path, lists: list[SignupList]) -> list[str]:
    """Make lists/ hold exactly one generated page per list. Returns changed paths.

    Only files carrying the generated marker are ever deleted.
    """
    changed = [f"{PAGES_DIR}/{lst.id}.html" for lst in lists if write_stub(root, lst.id)]
    ids = {lst.id for lst in lists}
    for path in sorted((root / PAGES_DIR).glob("*.html")):
        if path.stem not in ids and MARK in path.read_text(encoding="utf-8"):
            path.unlink()
            changed.append(f"{PAGES_DIR}/{path.name}")
    return changed
